function parseMarkdownClient(source, imageAssets) {
  'use strict';
  const limits = FMD_CLIENT_RENDER_LIMITS;
  let work = limits.workUnits, structures = limits.structures;
  function exhausted(limit) {
    const error = Error('Lightweight preview exceeds its ' + limit + ' limit. '
      + 'Markdown is unchanged and remains downloadable; use the native renderer for this document.');
    error.code = 'FMD_RENDER_LIMIT'; error.limit = limit;
    throw error;
  }
  function charge(units = 1) {
    if (units > work) exhausted('work');
    work -= units;
  }
  function allocate(units = 1) {
    if (units > structures) exhausted('structure');
    structures -= units;
  }
  function append(out, fragment) {
    if (fragment.length > limits.outputUnits - out.length) exhausted('output');
    charge(fragment.length + 1);
    return out + fragment;
  }
  // Charge searches as they advance, not the entire remaining suffix: ordinary
  // documents containing many short links must not incur a quadratic debit.
  function find(text, marker, start) {
    for (let i = start; i <= text.length - marker.length; i++) {
      charge(marker.length);
      if (text.startsWith(marker, i)) return i;
    }
    return -1;
  }
  function runEnd(text, start, ch) {
    let end = start;
    while (text[end] === ch) { charge(); end++; }
    return end;
  }
  source = String(source);
  if (source.length > limits.sourceUnits) exhausted('source');
  // Bound split() allocation before creating the line array, including CR-only
  // input. A source consisting only of newlines is not a cheap single block.
  charge(source.length);
  let lineCount = 1;
  for (let i = 0; i < source.length; i++) {
    if (source[i] === '\r') { lineCount++; if (source[i + 1] === '\n') i++; }
    else if (source[i] === '\n') lineCount++;
    if (lineCount > limits.structures) exhausted('structure');
  }
  allocate(lineCount);
  if (!imageAssets) imageAssets = new Map();
  const definitions = new Map(), notes = new Map(), usedNotes = [], headings = new Map();
  const MAX_DEPTH = 64;
  const escape = text => {
    text = String(text); charge(text.length);
    let length = text.length;
    if (length > limits.outputUnits) exhausted('output');
    return text.replace(/[&<>"']/g, ch => {
      const encoded = {'&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'}[ch];
      length += encoded.length - 1;
      if (length > limits.outputUnits) exhausted('output');
      return encoded;
    });
  };
  // Exact source IDs keep case-distinct footnotes and their bodies separate.
  const noteKey = label => { charge(label.length); return label; };
  function normalizeReference(label) {
    charge(label.length);
    // The 999-character cap applies to source scalars, before either whitespace
    // removal or a full-fold expansion. It also bounds inline reference uses.
    let characters = 0;
    for (const scalar of label) if (++characters > 999) return null;
    let key = '';
    for (const scalar of label.trim().replace(/\s+/g, ' ')) {
      const folded = fmdFoldReferenceScalar(scalar.codePointAt(0));
      charge(folded.length);
      key += folded;
    }
    return key;
  }
  // Decode before applying the URL policy, and escape once when emitting HTML.
  // Unknown named entities remain literal rather than gaining browser semantics.
  const decode = text => text.replace(/&(#x[0-9a-f]+|#\d+|amp|lt|gt|quot|apos|nbsp);/gi, (all, entity) => {
    if (entity[0] !== '#') return ({amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: '\u00a0'})[entity.toLowerCase()];
    const n = entity[1].toLowerCase() === 'x' ? parseInt(entity.slice(2), 16) : Number(entity.slice(1));
    return n > 0 && n <= 0x10ffff && !(n >= 0xd800 && n <= 0xdfff) ? String.fromCodePoint(n) : '\ufffd';
  });
  const unescape = text => { charge(text.length); return decode(text.replace(/\\([!"#$%&'()*+,\-./:;<=>?@[\]\\^_`{|}~])/g, '$1')); };
  function safeUrl(raw, image) {
    const url = unescape(raw).trim();
    // Bindings can replace image bytes, not turn a non-image data URL into an
    // image source. Match native admission before consulting an exact binding.
    if (image && /^data:/i.test(url) && !fmdDataImageMime(url)) return null;
    if (image && imageAssets.has(url)) {
      // An explicit binding replaces the destination, never grants permission
      // to fetch it. Revalidate saved data before emitting an attribute.
      const bound = imageAssets.get(url);
      // Reference images can expand a tiny source into a large payload. Admit
      // the bound data before validating it or copying it into an attribute.
      if (typeof bound === 'string') {
        if (bound.length > limits.outputUnits) exhausted('output');
        charge(bound.length);
      }
      return fmdEmbeddedImageUrl(bound) ? bound : null;
    }
    if (image && fmdEmbeddedImageUrl(url)) return url;
    if (image && /^data:/i.test(url)) {
      return fmdNormalizeSourceImage(url, charge, exhausted, limits.outputUnits);
    }
    if (/[\u0000-\u0020\u007f-\u009f]/.test(url)) return null;
    const scheme = url.match(/^([a-z][a-z0-9+.-]*):/i);
    if (scheme && !(image ? /^(https?)$/i : /^(https?|mailto|tel)$/i).test(scheme[1])) return null;
    // A backslash is a slash in browser URL parsing; do not accept its
    // protocol-relative spellings as an apparently local destination.
    if (url.includes('\\')) return null;
    return url;
  }
  const escapable = ch => /[!"#$%&'()*+,\-./:;<=>?@[\]\\^_`{|}~]/.test(ch || '');
  // Parse the complete suffix in its own grammar. Parentheses in angle URLs
  // and quoted titles are literal, and none of an accepted target's brackets,
  // backticks or emphasis markers belong to the surrounding inline content.
  function inlineTarget(text, close, bareParenEnd) {
    if (text[close + 1] !== '(') return null;
    let i = close + 2, url = '', title = '';
    const whitespace = () => {
      let newline = false;
      while (i < text.length) {
        charge();
        if (text[i] === '\n' && !newline) { newline = true; i++; }
        else if (' \t\r'.includes(text[i])) i++;
        else break;
      }
    };
    whitespace();
    if (text[i] === ')') return {url, title, end: i + 1};
    const angle = text[i] === '<', start = angle ? ++i : i;
    for (; i < text.length; i++) {
      charge();
      const ch = text[i];
      if (ch === '\\' && escapable(text[i + 1])) { charge(); i++; continue; }
      if (angle) {
        if (ch === '>') break;
        if (ch === '\n' || ch === '<') return null;
      } else {
        if (' \t\r\n'.includes(ch) || ch === ')') break;
        if (ch === '<' || /[\u0000-\u001f\u007f]/.test(ch)) return null;
        if (ch === '(') {
          const end = bareParenEnd(i);
          if (end === undefined) return null;
          i = end;
        }
      }
    }
    if (angle ? text[i] !== '>' : i === start) return null;
    url = text.slice(start, i);
    if (angle) i++;
    const spaces = i;
    whitespace();
    if (text[i] !== ')') {
      if (i === spaces || !['"', "'", '('].includes(text[i])) return null;
      const quote = text[i++], endQuote = quote === '(' ? ')' : quote, titleStart = i;
      let newline = false;
      for (; i < text.length; i++) {
        charge();
        const ch = text[i];
        if (ch === endQuote) break;
        if (quote === '(' && ch === '(') return null;
        if (ch === '\\' && escapable(text[i + 1])) { charge(); i++; newline = false; continue; }
        if (ch === '\n') { if (newline) return null; newline = true; }
        else if (!/\s/.test(ch)) newline = false;
      }
      if (text[i] !== endQuote) return null;
      const titleEnd = i++;
      whitespace();
      if (text[i] !== ')') return null;
      title = unescape(text.slice(titleStart, titleEnd));
    }
    return text[i] === ')' ? {url, title, end: i + 1} : null;
  }
  // A full reference's suffix is raw source: even an unmatched backtick cannot
  // hide its closing bracket. Malformed suffixes still permit shortcut links.
  function referenceLabel(text, open) {
    if (text[open] !== '[') return null;
    let i = open + 1, characters = 0;
    while (i < text.length && characters <= 999) {
      charge();
      if (text[i] === ']') return {label: text.slice(open + 1, i), end: i + 1};
      if (text[i] === '[') return null;
      if (text[i] === '\\' && i + 1 < text.length) { i++; characters++; charge(); }
      i += text.codePointAt(i) > 0xffff ? 2 : 1;
      characters++;
    }
    return null;
  }
  function targetAfter(text, open, close, bareParenEnd) {
    const target = inlineTarget(text, close, bareParenEnd);
    if (target) return target;
    const suffix = referenceLabel(text, close + 1);
    const label = suffix?.label || text.slice(open + 1, close);
    const reference = definitions.get(normalizeReference(label));
    return reference ? {...reference, end: suffix ? suffix.end : close + 1} : null;
  }
  // Only nested bare-URL groups use these pairs. Whitespace, controls and raw
  // '<' end a bare destination, so an opener cannot match across them. Sharing
  // this lazy index prevents repeated incomplete links from rescanning the
  // entire suffix; angle destinations and titles retain their own grammars.
  function bareParenthesisPairs(text) {
    const stack = [], pairs = new Map();
    for (let i = 0; i < text.length; i++) {
      charge();
      const ch = text[i];
      if (ch === '\\' && escapable(text[i + 1])) { charge(); i++; continue; }
      if (ch === '(') { allocate(); stack.push(i); }
      else if (ch === ')' && stack.length) { allocate(); pairs.set(stack.pop(), i); }
      else if (ch === '<' || ch.charCodeAt(0) <= 32 || ch === '\x7f') stack.length = 0;
    }
    return pairs;
  }
  // Raw footnote identifiers keep their existing exact-source semantics. Link
  // labels use the contextual index below instead of this lexical pairing.
  function rawBracketPairs(text) {
    charge(text.length);
    const stack = [], pairs = new Map();
    for (let i = 0; i < text.length; i++) {
      if (text[i] === '\\') { i++; continue; }
      if (text[i] === '[') { allocate(); stack.push(i); }
      else if (text[i] === ']' && stack.length) {
        allocate(); pairs.set(stack.pop(), i);
      }
    }
    return pairs;
  }
  function uniqueId(slug) {
    let id = slug, suffix = headings.get(slug) || 0;
    while (headings.has(id)) { charge(id.length + 1); id = slug + '-' + (++suffix); }
    allocate();
    headings.set(slug, suffix); headings.set(id, 0);
    return id;
  }
  function noteReference(label) {
    const key = noteKey(label), note = notes.get(key);
    if (!note) return null;
    if (!note.number) { note.number = usedNotes.length + 1; note.id = uniqueId('fn-' + note.number); note.referenceIds = []; usedNotes.push(note); }
    allocate(); charge();
    note.references++;
    const id = uniqueId('fnref-' + note.number + (note.references > 1 ? '-' + note.references : ''));
    note.referenceIds.push(id);
    return '<sup class="footnote-ref" id="' + id + '"><a href="#' + note.id + '" role="doc-noteref">' + note.number + '</a></sup>';
  }
  function emailAddress(label) {
    // The former pair of greedy domain classes backtracked quadratically on
    // a long dotted domain ending in a second '@'. Keep the same subset with
    // independent linear checks, including its permissive trailing-dot cases.
    charge(label.length * 3 + 1);
    const at = label.indexOf('@');
    if (at < 1 || label.indexOf('@', at + 1) >= 0 || /[\s<>]/.test(label)) return false;
    const dot = label.indexOf('.', at + 2);
    return dot >= 0 && dot < label.length - 1;
  }
  function codeExtent(text, start) {
    const content = runEnd(text, start, '`'), marker = text.slice(start, content);
    let close = content;
    while ((close = find(text, marker, close)) >= 0) {
      if (text[close - 1] !== '`' && text[close + marker.length] !== '`') {
        return {kind: 'code', content, close, end: close + marker.length};
      }
      close += marker.length;
    }
    return {end: content};
  }
  function autolinkAt(text, start) {
    const close = find(text, '>', start + 1);
    if (close < 0) return null;
    const label = text.slice(start + 1, close), email = emailAddress(label);
    const uri = /^[a-z][a-z0-9+.-]*:/i.test(label) && !/[\s<\u0000-\u001f\u007f-\u009f]/.test(label);
    return email || uri
      ? {kind: 'autolink', label, url: email ? 'mailto:' + label : label, end: close + 1} : null;
  }
  function inlineIndex(text) {
    const atoms = new Map(), stack = [];
    let rawBrackets, bareParens;
    const bareParenEnd = start => (bareParens ??= bareParenthesisPairs(text)).get(start);
    const remember = (start, atom) => { allocate(); atoms.set(start, atom); };
    for (let i = 0; i < text.length;) {
      charge();
      const ch = text[i];
      if (ch === '\\' && (escapable(text[i + 1]) || text[i + 1] === '\n')) { i += 2; continue; }
      if (ch === '`') {
        const code = codeExtent(text, i);
        if (code.kind) remember(i, code);
        i = code.end; continue;
      }
      if (ch === '<') {
        const link = autolinkAt(text, i);
        if (link) {
          remember(i, link);
          if (stack.length) stack.at(-1).containsLink = true;
          i = link.end; continue;
        }
      }
      const image = ch === '!' && text[i + 1] === '[';
      if (image || ch === '[') {
        if (!image && text[i + 1] === '^' && notes.size) {
          const close = (rawBrackets ??= rawBracketPairs(text)).get(i);
          const label = close === undefined ? null : text.slice(i + 2, close);
          if (label !== null && notes.has(noteKey(label))) {
            remember(i, {kind: 'note', label, end: close + 1});
            i = close + 1; continue;
          }
        }
        allocate();
        stack.push({start: i, open: i + (image ? 1 : 0), image, containsLink: false});
        i += image ? 2 : 1; continue;
      }
      if (ch === ']' && stack.length) {
        const open = stack.pop();
        const target = open.image || !open.containsLink ? targetAfter(text, open.open, i, bareParenEnd) : null;
        if (target) {
          remember(open.start, {kind: open.image ? 'image' : 'link', labelStart: open.open + 1, labelEnd: i, ...target});
          if (!open.image && stack.length) stack.at(-1).containsLink = true;
          i = target.end; continue;
        }
        // An accepted image contains its child links as alt text. A rejected
        // label propagates them, preventing an enclosing anchor from nesting.
        if (open.containsLink && stack.length) stack.at(-1).containsLink = true;
      }
      i++;
    }
    return atoms;
  }
  function inline(text, depth = 0, links = true, footnotes = true, images = true, table = false) {
    charge(text.length + 1);
    if (depth > MAX_DEPTH) return escape(text);
    const atoms = inlineIndex(text);
    let out = '', i = 0;
    while (i < text.length) {
      charge();
      const atom = atoms.get(i);
      if (atom) {
        if (atom.kind === 'code') {
          let code = text.slice(atom.content, atom.close).replace(/\n/g, ' ');
          if (code.startsWith(' ') && code.endsWith(' ') && /[^ ]/.test(code)) code = code.slice(1, -1);
          if (table) code = code.replace(/\\\|/g, '|');
          out = append(out, '<code>' + escape(code) + '</code>');
        } else if (atom.kind === 'note') {
          out = append(out, footnotes ? noteReference(atom.label) : escape(text.slice(i, atom.end)));
        } else if (atom.kind === 'autolink') {
          const url = links ? safeUrl(atom.url, false) : null;
          out = append(out, !links ? escape(atom.label) : url === null ? escape(text.slice(i, atom.end))
            : '<a href="' + escape(url) + '">' + escape(atom.label) + '</a>');
        } else {
          const image = atom.kind === 'image';
          const content = inline(text.slice(atom.labelStart, atom.labelEnd), depth + 1, false, false, images && !image, table);
          // Only emitted images consult embedded assets. Nested images in alt
          // text contribute their own readable labels without hidden expansion.
          const url = (image ? images : links) ? safeUrl(atom.url, image) : null;
          const title = atom.title ? ' title="' + escape(atom.title) + '"' : '';
          if (image) {
            const alt = content.replace(/<[^>]*>/g, '');
            out = append(out, url === null ? alt : '<img src="' + escape(url) + '" alt="' + alt + '"' + title + '>');
          } else out = append(out, url === null ? content : '<a href="' + escape(url) + '"' + title + '>' + content + '</a>');
        }
        i = atom.end; continue;
      }
      const ch = text[i];
      if (ch === '\\' && text[i + 1] === '\n') { out = append(out, '<br>\n'); i += 2; continue; }
      if (ch === '\\' && escapable(text[i + 1])) {
        out = append(out, escape(text[i + 1])); i += 2; continue;
      }
      if (ch === ' ') {
        const end = runEnd(text, i, ' '), run = text.slice(i, end);
        if (text[end] === '\n') { out = append(out, run.length >= 2 ? '<br>\n' : '\n'); i = end + 1; continue; }
        out = append(out, run); i = end; continue;
      }
      if (ch === '`') {
        const marker = text.slice(i, runEnd(text, i, '`'));
        out = append(out, marker); i += marker.length; continue;
      }
      if ('*_~'.includes(ch)) {
        // Never interpret intraword underscores or single tildes as delimiters.
        const run = text.slice(i, runEnd(text, i, ch));
        const size = ch === '~' ? (run.length >= 2 ? 2 : 0) : Math.min(run.length, 3);
        const marker = ch.repeat(size);
        if (size && !/\s/.test(text[i + size] || ' ') && !(ch === '_' && /[\p{L}\p{N}]/u.test(text[i - 1] || ''))) {
          let end = i + size;
          for (; end <= text.length - size; end++) {
            charge(size);
            const owned = atoms.get(end);
            if (owned) { end = owned.end - 1; continue; }
            if (text[end] === '\\' && escapable(text[end + 1])) { end++; continue; }
            if (text.startsWith(marker, end) && !/\s/.test(text[end - 1])
                && !(ch === '_' && /[\p{L}\p{N}]/u.test(text[end + size] || ''))) break;
          }
          if (end > text.length - size) end = -1;
          if (end > i + size) {
            const tags = ch === '~' ? ['del'] : size === 3 ? ['strong', 'em'] : [size === 2 ? 'strong' : 'em'];
            out = append(out, tags.map(t => '<' + t + '>').join('') + inline(text.slice(i + size, end), depth + 1, links, footnotes, images, table) + tags.slice().reverse().map(t => '</' + t + '>').join(''));
            i = end + size; continue;
          }
        }
      }
      if (ch === '&') {
        const entity = text.slice(i).match(/^&(?:#x[0-9a-f]+|#\d+|amp|lt|gt|quot|apos|nbsp);/i);
        if (entity) { out = append(out, escape(decode(entity[0]))); i += entity[0].length; continue; }
      }
      out = append(out, escape(ch)); i++;
    }
    return out;
  }
  // Only ASCII space and tab make a CommonMark blank line. In particular, a
  // BOM or NBSP inside a literal block must not terminate or disappear from it.
  const blankLine = line => /^[ \t]*$/.test(line);
  const htmlBlockTags = new Set(('address article aside base basefont blockquote body caption center col colgroup dd details dialog dir div dl dt '
    + 'fieldset figcaption figure footer form frame frameset h1 h2 h3 h4 h5 h6 head header hr html iframe legend li link main menu menuitem nav '
    + 'noframes ol optgroup option p param search section summary table tbody td tfoot th thead title tr track ul').split(' '));
  const asciiLetter = code => code >= 65 && code <= 90 || code >= 97 && code <= 122;
  const asciiDigit = code => code >= 48 && code <= 57;
  // Return CommonMark's HTML block type (1..7), or zero. This recognizes source
  // grammar only: lightweight output keeps its existing inert-markup policy.
  // Scan complete type-seven tags once; no accumulated-line regex or DOM parser
  // may consume definitions, fetch resources, or gain authority over the source.
  function htmlBlockKind(line) {
    let pos = 0;
    while (pos < 3 && line[pos] === ' ') pos++;
    if (line[pos] !== '<') return 0;
    charge();
    if (line.startsWith('<!--', pos)) return 2;
    if (line.startsWith('<?', pos)) return 3;
    if (line.startsWith('<![CDATA[', pos)) return 5;
    if (line.startsWith('<!', pos)) return asciiLetter(line.charCodeAt(pos + 2)) ? 4 : 0;
    const closing = line[pos + 1] === '/';
    pos += closing ? 2 : 1;
    const nameStart = pos;
    if (!asciiLetter(line.charCodeAt(pos))) return 0;
    pos++;
    while (asciiLetter(line.charCodeAt(pos)) || asciiDigit(line.charCodeAt(pos)) || line[pos] === '-') {
      charge(); pos++;
    }
    charge(pos - nameStart);
    const name = line.slice(nameStart, pos).toLowerCase();
    const raw = name === 'pre' || name === 'script' || name === 'style' || name === 'textarea';
    const boundary = pos === line.length || line[pos] === ' ' || line[pos] === '\t' || line[pos] === '>';
    if (!closing && raw && boundary) return 1;
    if (htmlBlockTags.has(name) && (boundary || line.startsWith('/>', pos))) return 6;
    // Raw-text opening names cannot use type seven's self-closing spelling.
    // Complete closing tags with those names can start a type-seven block.
    if (!closing && raw) return 0;
    const space = () => { while (line[pos] === ' ' || line[pos] === '\t') { charge(); pos++; } };
    const end = () => {
      if (line[pos] !== '>') return 0;
      pos++; space();
      return pos === line.length ? 7 : 0;
    };
    if (closing) { space(); return end(); }
    while (pos < line.length) {
      charge();
      const beforeSpace = pos;
      space();
      if (line[pos] === '>') return end();
      if (line[pos] === '/') { pos++; return end(); }
      // Attributes need separating whitespace and ASCII names, even when their
      // quoted values contain angle brackets or arbitrary non-ASCII text.
      if (pos === beforeSpace || !(asciiLetter(line.charCodeAt(pos)) || line[pos] === '_' || line[pos] === ':')) return 0;
      pos++;
      while (asciiLetter(line.charCodeAt(pos)) || asciiDigit(line.charCodeAt(pos)) || '_.:-'.includes(line[pos] ?? '\0')) {
        charge(); pos++;
      }
      const nameEnd = pos;
      space();
      if (line[pos] !== '=') { pos = nameEnd; continue; }
      pos++; space();
      const quote = line[pos];
      if (quote === '"' || quote === "'") {
        pos++;
        while (pos < line.length && line[pos] !== quote) { charge(); pos++; }
        if (line[pos] !== quote) return 0;
        pos++;
      } else {
        const valueStart = pos;
        while (pos < line.length && !' \t\r\n"\'=<>`'.includes(line[pos])) { charge(); pos++; }
        if (pos === valueStart) return 0;
      }
    }
    return 0;
  }
  function htmlBlockEnded(kind, line) {
    if (kind >= 6) return blankLine(line);
    charge(line.length + 1);
    switch (kind) {
      case 1: return /<\/(?:script|pre|style|textarea)>/i.test(line);
      case 2: return line.includes('-->');
      case 3: return line.includes('?>');
      case 4: return line.includes('>');
      case 5: return line.includes(']]>');
    }
    return false;
  }
  function htmlInterruptsParagraph(line) {
    const kind = htmlBlockKind(line);
    return kind !== 0 && kind !== 7;
  }
  const fence = line => {
    const match = line.match(/^ {0,3}(`{3,}|~{3,})(.*)$/);
    return match && !(match[1][0] === '`' && match[2].includes('`')) ? match : null;
  };
  const fenceEnd = marker => new RegExp('^ {0,3}' + marker[0] + '{' + marker.length + ',}[ \\t]*$');
  const rule = line => /^ {0,3}(?:(?:\* *){3,}|(?:- *){3,}|(?:_ *){3,})$/.test(line);
  const headingMarker = line => line.match(/^ {0,3}(#{1,6})(?:[ \t]+(.*)|$)/);
  const setextLevel = line => /^ {0,3}=+[ \t]*$/.test(line) ? 1 : /^ {0,3}-+[ \t]*$/.test(line) ? 2 : 0;
  const footnoteMarker = line => line.match(/^ {0,3}\[\^([^\]]+)\]:[ \t]*(.*)$/);
  function indentation(line, startColumn = 0) {
    let end = 0, column = startColumn;
    while (line[end] === ' ' || line[end] === '\t') {
      charge();
      column += line[end++] === '\t' ? 4 - column % 4 : 1;
    }
    return {end, width: column - startColumn};
  }
  function stripIndent(line, columns, startColumn = 0) {
    const indent = indentation(line, startColumn), remaining = Math.max(0, indent.width - columns);
    charge(remaining + 1);
    return ' '.repeat(remaining) + line.slice(indent.end);
  }
  function stripQuote(line) {
    const marker = line.match(/^ {0,3}>/);
    if (!marker) return null;
    const rest = line.slice(marker[0].length);
    if (rest[0] === '\t') return stripIndent(rest, 1, marker[0].length);
    return rest[0] === ' ' ? rest.slice(1) : rest;
  }
  const listMarker = line => {
    const m = line.match(/^( {0,3})([-+*]|\d{1,9}[.)])(?:([ \t]+)(.*)|$)/);
    if (!m) return null;
    const column = m[1].length + m[2].length;
    const gap = indentation(m[3] || ' ', column).width;
    return {indent: m[1].length, marker: m[2], ordered: /^\d/.test(m[2]),
      start: parseInt(m[2], 10), width: column + (gap > 4 ? 1 : gap),
      text: gap > 4 ? stripIndent(m[3] + (m[4] || ''), 1, column) : m[4] || ''};
  };
  const markerInterrupts = marker => marker && !blankLine(marker.text) && (!marker.ordered || marker.start === 1);
  const startsBlock = line => blankLine(line) || fence(line) || headingMarker(line) || /^ {0,3}>/.test(line) || rule(line) || listMarker(line) || htmlBlockKind(line);
  const interruptsParagraph = line => blankLine(line) || fence(line) || headingMarker(line) || /^ {0,3}>/.test(line) || rule(line) || markerInterrupts(listMarker(line)) || htmlInterruptsParagraph(line);
  // Table rows admit ordinary pipe-bearing source. A supported block opener
  // retains its own scope even when it also contains a pipe character.
  const tableRowSource = line => line.includes('|') && !startsBlock(line)
    && indentation(line).width < 4 && !footnoteMarker(line);
  function lazyLine(line) {
    const trimmed = line.replace(/^[ \t]+/, '');
    // Removing indentation must not promote a lazy line into a setext heading
    // or nested list. The escape is consumed by normal inline parsing.
    return setextLevel(trimmed) || (listMarker(trimmed) && !listMarker(line)) ? '\\' + trimmed : trimmed;
  }
  function tableCells(line) {
    charge(line.length + 1);
    line = line.trim();
    if (line.startsWith('|')) line = line.slice(1);
    // Match maximal backtick runs by length once. Unmatched runs remain text,
    // and escaped openers may leave a shorter run that closes at a later run.
    // This protects the native extension for unescaped code pipes without
    // repeatedly searching every remaining suffix of an adversarial row.
    const codeRuns = new Map();
    for (let i = 0; i < line.length;) {
      charge();
      if (line[i] === '`') {
        const end = runEnd(line, i, '`'), size = end - i;
        if (!codeRuns.has(size)) { allocate(); codeRuns.set(size, []); }
        allocate(); codeRuns.get(size).push(i); i = end;
      } else i++;
    }
    const cells = [];
    let start = 0, i = 0;
    while (i < line.length) {
      charge();
      if (line[i] === '\\') { i += i + 1 < line.length ? 2 : 1; continue; }
      if (line[i] === '`') {
        const end = runEnd(line, i, '`'), size = end - i, runs = codeRuns.get(size) || [];
        let low = 0, high = runs.length;
        while (low < high) {
          charge();
          const middle = low + Math.floor((high - low) / 2);
          if (runs[middle] < end) low = middle + 1;
          else high = middle;
        }
        i = low < runs.length ? runs[low] + size : end; continue;
      }
      if (line[i] === '|') {
        allocate(); cells.push(line.slice(start, i).trim()); start = i + 1;
      }
      i++;
    }
    // An escaped final pipe belongs to its cell; only a real separator is
    // optional. Preserve raw labels/destinations for their normal inline rules.
    if (start < line.length || !line.length) { allocate(); cells.push(line.slice(start).trim()); }
    return cells;
  }
  function tableAlignments(header, delimiter) {
    charge(header.length + 1);
    if (!tableRowSource(header)) return null;
    const cells = tableCells(delimiter);
    if (cells.length !== tableCells(header).length || !cells.every(c => /^:?-+:?$/.test(c))) return null;
    return cells.map(c => c.startsWith(':') && c.endsWith(':') ? 'center' : c.endsWith(':') ? 'right' : c.startsWith(':') ? 'left' : '');
  }
  function headingTitle(text) {
    charge(text.length);
    let end = text.length;
    while (end > 0 && /[ \t]/.test(text[end - 1])) end--;
    let hashes = end;
    while (hashes > 0 && text[hashes - 1] === '#') hashes--;
    if (hashes < end && hashes > 0 && /[ \t]/.test(text[hashes - 1])) {
      while (hashes > 0 && /[ \t]/.test(text[hashes - 1])) hashes--;
      text = text.slice(0, hashes);
    }
    return text.trim();
  }
  // Reference definitions have a different grammar from inline destinations:
  // their label, destination and title can continue onto subsequent lines. A
  // cursor reads only this candidate, never joins the remaining document. All
  // speculative scans debit the same invocation-wide work budget.
  function referenceDefinition(lines, start) {
    let line = start, column = 0;
    while (lines[line][column] === ' ' && column < 3) column++;
    if (lines[line][column] !== '[' || lines[line][column + 1] === '^') return null;
    column++;
    let label = '', characters = 0;
    while (line < lines.length) {
      charge();
      const text = lines[line], ch = text[column];
      if (ch === undefined) {
        if (line + 1 >= lines.length) return null;
        charge(lines[line + 1].length + 1);
        if (!lines[line + 1].trim()) return null;
        label += '\n'; characters++; line++; column = 0;
      } else if (ch === ']') {
        column++;
        if (text[column] !== ':' || !label.trim()) return null;
        column++; break;
      } else {
        if (ch === '[') return null;
        if (ch === '\\' && column + 1 < text.length && /[!"#$%&'()*+,\-./:;<=>?@[\]\\^_`{|}~]/.test(text[column + 1])) {
          label += text.slice(column, column + 2); column += 2; characters += 2;
        } else {
          const width = text.codePointAt(column) > 0xffff ? 2 : 1;
          label += text.slice(column, column + width); column += width; characters++;
        }
      }
      if (characters > 999) return null;
    }
    function spaces() {
      const begin = column;
      while (lines[line][column] === ' ' || lines[line][column] === '\t') { charge(); column++; }
      return column - begin;
    }
    spaces();
    if (column === lines[line].length) {
      if (line + 1 >= lines.length) return null;
      line++; column = 0; spaces();
      if (column === lines[line].length) return null; // no blank line before a destination
    }
    const text = lines[line];
    let url;
    if (text[column] === '<') {
      const begin = ++column;
      while (column < text.length && text[column] !== '>') {
        charge();
        if (text[column] === '<') return null;
        if (text[column] === '\\' && column + 1 < text.length) column += 2;
        else column++;
      }
      if (text[column] !== '>') return null;
      url = text.slice(begin, column++); // <> is a valid empty destination
    } else {
      const begin = column;
      let nesting = 0;
      while (column < text.length && text[column] !== ' ' && text[column] !== '\t') {
        charge();
        const ch = text[column];
        if (ch.charCodeAt(0) < 32 || ch.charCodeAt(0) === 127) return null;
        if (ch === '\\' && column + 1 < text.length && /[!"#$%&'()*+,\-./:;<=>?@[\]\\^_`{|}~]/.test(text[column + 1])) {
          column += 2; continue;
        }
        if (ch === '(') nesting++;
        else if (ch === ')' && --nesting < 0) return null;
        column++;
      }
      if (nesting || column === begin) return null;
      url = text.slice(begin, column);
    }
    const destinationLine = line, gap = spaces();
    function titleAt(row, col) {
      const open = lines[row][col], close = open === '(' ? ')' : open;
      if (open !== '"' && open !== "'" && open !== '(') return null;
      col++;
      let title = '';
      while (row < lines.length) {
        charge();
        const text = lines[row], ch = text[col];
        if (ch === undefined) {
          if (row + 1 >= lines.length) return null;
          charge(lines[row + 1].length + 1);
          if (!lines[row + 1].trim()) return null;
          title += '\n'; row++; col = 0; continue;
        }
        if (ch === close) {
          charge(text.length - col);
          if (!/^[ \t]*$/.test(text.slice(col + 1))) return null;
          return {title: unescape(title), end: row};
        }
        if (open === '(' && ch === '(') return null;
        if (ch === '\\' && col + 1 < text.length && /[!"#$%&'()*+,\-./:;<=>?@[\]\\^_`{|}~]/.test(text[col + 1])) {
          title += text.slice(col, col + 2); col += 2;
        } else { title += ch; col++; }
      }
      return null;
    }
    if (column < lines[line].length) {
      if (!gap) return null;
      const result = titleAt(line, column);
      return result ? {label, url, title: result.title, consumed: result.end - start + 1} : null;
    }
    // A malformed same-line title invalidates the whole definition. A malformed
    // next-line title leaves the already-valid URL definition in place and the
    // untouched candidate line available for normal block parsing.
    if (line + 1 < lines.length) {
      line++; column = 0; spaces();
      const result = titleAt(line, column);
      if (result) return {label, url, title: result.title, consumed: result.end - start + 1};
    }
    return {label, url, title: '', consumed: destinationLine - start + 1};
  }
  // Constant-size recognition state for a reference candidate crossing physical
  // lines. Container collection must not treat title text as a fence or heading,
  // and must never repeatedly reparse an accumulated label/title prefix.
  function referenceTail() {
    let phase = 'label', lines = 0, characters = 0, hasText = false;
    let escaped = false, nesting = 0, separated = false, close = '';
    const punctuation = ch => /[!"#$%&'()*+,\-./:;<=>?@[\]\\^_`{|}~]/.test(ch);
    return line => {
      if (!line.trim()) return null;
      if (!lines++) {
        const trimmed = line.replace(/^[ \t]+/, '');
        if (indentation(line).width > 3 || !trimmed.startsWith('[')) return null;
        line = trimmed.slice(1);
      }
      for (const ch of line) {
        charge();
        switch (phase) {
          case 'label':
            if (!escaped && ch === ']') {
              if (!hasText) return null;
              phase = 'colon'; break;
            }
            if (!escaped && ch === '[') return null;
            if (++characters > 999) return null;
            hasText ||= !/\s/.test(ch);
            escaped = !escaped && ch === '\\'; break;
          case 'colon':
            if (ch !== ':') return null;
            phase = 'start'; break;
          case 'start':
            if (ch === ' ' || ch === '\t') break;
            if (ch === '<') { phase = 'angle'; break; }
            if (ch === ')' || ch.charCodeAt(0) < 32 || ch === '\x7f') return null;
            phase = 'bare'; nesting = ch === '(' ? 1 : 0; escaped = ch === '\\'; break;
          case 'angle': case 'bare':
            if (escaped) { escaped = false; if (punctuation(ch)) break; }
            if (ch === '\\') { escaped = true; break; }
            if (ch === '<') return null;
            if (phase === 'angle') {
              if (ch === '>') { phase = 'after'; separated = false; }
              break;
            }
            if ((ch === ' ' || ch === '\t') && !nesting) { phase = 'after'; separated = true; break; }
            if (ch === '(') nesting++;
            else if (ch === ')') { if (!nesting) return null; nesting--; }
            else if (ch.charCodeAt(0) < 32 || ch === '\x7f' || ch === ' ') return null;
            break;
          case 'after': case 'nextTitle':
            if (ch === ' ' || ch === '\t') { separated = true; break; }
            if (!separated || !['"', "'", '('].includes(ch)) return null;
            close = ch === '(' ? ')' : ch; phase = 'title'; escaped = false; break;
          case 'title':
            if (escaped) { escaped = false; if (punctuation(ch)) break; }
            if (ch === close) phase = 'done';
            else if (ch === '(' && close === ')') return null;
            else escaped = ch === '\\';
            break;
          case 'done':
            if (ch !== ' ' && ch !== '\t') return null;
        }
      }
      escaped = false;
      if (phase === 'label') return ++characters <= 999 ? 'pending' : null;
      if (phase === 'start' || phase === 'title') return 'pending';
      if ((phase === 'bare' && !nesting) || phase === 'after') {
        phase = 'nextTitle'; separated = true; return 'destination';
      }
      return phase === 'done' ? 'title' : null;
    };
  }
  // A list or quote can lazily extend only its current paragraph leaf. Track
  // nested containers and literal blocks in one pass, bounded by MAX_DEPTH;
  // inspecting only the previous line loses both code and reference ownership.
  function containerTail(depth) {
    const containers = [];
    let kind = 'boundary', header = null, closing = null, reference = null, htmlKind = 0;
    const canContinue = line => kind === 'paragraph' && !interruptsParagraph(line);
    function observe(line, level = 0) {
      charge(line.length + 1);
      const container = containers[level];
      if (container) {
        let sibling = false;
        if (container.kind === 'quote') {
          const inner = stripQuote(line);
          if (inner !== null) { observe(inner, level + 1); return; }
        } else {
          if (blankLine(line) || indentation(line).width >= container.width) {
            observe(stripIndent(line, container.width), level + 1); return;
          }
          const next = listMarker(line);
          sibling = next && ((next.indent === container.indent && next.ordered === container.ordered) || markerInterrupts(next));
        }
        if (!sibling && canContinue(line)) return;
        containers.length = level; kind = 'boundary'; reference = null;
      }
      if (reference) {
        const progress = reference(line);
        if (progress) {
          kind = 'paragraph'; header = null;
          if (progress === 'title') reference = null;
          return;
        }
        reference = null;
      }
      if (kind === 'html') {
        if (htmlBlockEnded(htmlKind, line)) kind = 'boundary';
        return;
      }
      if (kind === 'fence') {
        if (closing.test(line)) kind = 'boundary';
        return;
      }
      if ((kind === 'code' || kind === 'footnote') && (blankLine(line) || indentation(line).width >= 4)) return;
      if (kind === 'table' && tableRowSource(line)) return;
      if (kind === 'paragraph' && !blankLine(line)) {
        if (header !== null && tableAlignments(header, line)) { kind = 'table'; header = null; return; }
        if (setextLevel(line)) { kind = 'boundary'; return; }
        if (!interruptsParagraph(line)) { header = null; return; }
      }
      kind = 'boundary'; header = null;
      if (blankLine(line) || rule(line) || headingMarker(line)) return;
      const fm = fence(line);
      if (fm) {
        kind = 'fence'; closing = fenceEnd(fm[1]); return;
      }
      if (indentation(line).width >= 4) { kind = 'code'; return; }
      if (footnoteMarker(line)) { kind = 'footnote'; return; }
      const inner = stripQuote(line);
      if (inner !== null) {
        if (depth + level < MAX_DEPTH) {
          allocate(); containers.push({kind: 'quote'}); observe(inner, level + 1);
        }
        return;
      }
      htmlKind = htmlBlockKind(line);
      if (htmlKind) {
        kind = htmlKind < 6 && htmlBlockEnded(htmlKind, line) ? 'boundary' : 'html';
        return;
      }
      const marker = listMarker(line);
      if (marker) {
        if (depth + level < MAX_DEPTH) {
          allocate(); containers.push({kind: 'list', indent: marker.indent, width: marker.width, ordered: marker.ordered});
          observe(marker.text.replace(/^\[([ xX])\](?:\s+|$)/, ''), level + 1);
        }
        return;
      }
      kind = 'paragraph';
      if (line.replace(/^[ \t]+/, '').startsWith('[')) {
        const scan = referenceTail(), progress = scan(line);
        if (progress) { if (progress !== 'title') reference = scan; return; }
      }
      header = line.includes('|') ? line : null;
    }
    return {observe, canContinue, literal: () => kind === 'fence' || kind === 'code' || kind === 'html',
      literalBlank: () => (kind === 'fence' || kind === 'html' && htmlKind < 6)
        && !containers.some(container => container.kind === 'quote')};
  }
  // Parse container structure exactly once, before rendering any inline text.
  // A global line pre-pass cannot distinguish a definition at the start of a
  // list item from the same spelling inside its code fence or paragraph. Keep
  // definition collection on this shared block path; never reconstruct source
  // after stripping definitions, which can change list/heading/table structure.
  function parseBlocks(lines, depth = 0) {
    for (const line of lines) charge(line.length + 1);
    const out = [];
    const push = node => { allocate(); out.push(node); };
    if (depth > MAX_DEPTH) {
      push({kind: 'fallback', text: lines.join('\n')});
      return out;
    }
    let i = 0;
    while (i < lines.length) {
      const line = lines[i];
      if (blankLine(line)) { i++; continue; }
      const fm = fence(line);
      if (fm && !(fm[1][0] === '`' && fm[2].includes('`'))) {
        const code = [], end = fenceEnd(fm[1]);
        const indent = line.length - line.trimStart().length;
        i++;
        while (i < lines.length && !end.test(lines[i])) code.push(lines[i++].replace(new RegExp('^ {0,' + indent + '}'), ''));
        if (i < lines.length) i++;
        const lang = unescape(fm[2].trim().split(/\s+/)[0]);
        push({kind: 'code', lang, text: code.join('\n') + (code.length ? '\n' : '')}); continue;
      }
      if (/^( {4}|\t)/.test(line)) {
        const code = [];
        while (i < lines.length && (/^( {4}|\t)/.test(lines[i]) || blankLine(lines[i]))) code.push(lines[i++].replace(/^( {4}|\t)/, ''));
        while (code.length && blankLine(code.at(-1))) code.pop();
        push({kind: 'code', lang: '', text: code.join('\n') + '\n'}); continue;
      }
      const htmlKind = htmlBlockKind(line);
      if (htmlKind) {
        const start = i++;
        if (htmlKind >= 6) {
          while (i < lines.length && !blankLine(lines[i])) i++;
        } else {
          let ended = htmlBlockEnded(htmlKind, line);
          while (i < lines.length && !ended) ended = htmlBlockEnded(htmlKind, lines[i++]);
        }
        push({kind: 'html', text: lines.slice(start, i).join('\n')}); continue;
      }
      // Only block starts can own definitions: these checks are deliberately
      // absent from paragraph continuation and table/code leaf parsing.
      const foot = footnoteMarker(line);
      if (foot) {
        const content = [foot[2]]; i++;
        while (i < lines.length) {
          if (blankLine(lines[i])) {
            let next = i;
            while (next < lines.length && blankLine(lines[next])) {
              charge(lines[next].length + 1); next++;
            }
            if (next === lines.length || indentation(lines[next]).width < 4) break;
            // Consume the complete admitted blank run once, retaining literal
            // blank content inside code instead of repeatedly scanning suffixes.
            while (i < next) content.push(stripIndent(lines[i++], 4));
          } else if (indentation(lines[i]).width >= 4) content.push(stripIndent(lines[i++], 4));
          else break;
        }
        const key = noteKey(foot[1]);
        if (!notes.has(key)) {
          allocate();
          // Reserve before descending: a nested duplicate cannot take the
          // identity of its earlier containing definition, including cycles.
          const note = {content: [], references: 0, number: 0};
          notes.set(key, note);
          note.content = parseBlocks(content, depth + 1);
        }
        continue;
      }
      const ref = referenceDefinition(lines, i);
      if (ref) {
        const key = normalizeReference(ref.label);
        if (!definitions.has(key)) { allocate(); definitions.set(key, {url: ref.url, title: ref.title}); }
        i += ref.consumed; continue;
      }
      let heading = headingMarker(line), title, level;
      if (heading) { level = heading[1].length; title = headingTitle(heading[2] || ''); i++; }
      if (level) { push({kind: 'heading', title, level}); continue; }
      if (rule(line)) { push({kind: 'rule'}); i++; continue; }
      if (/^ {0,3}>/.test(line)) {
        const quote = [], tail = containerTail(depth);
        while (i < lines.length) {
          let inner = stripQuote(lines[i]);
          if (inner === null) {
            if (!tail.canContinue(lines[i])) break;
            inner = lazyLine(lines[i]);
          }
          tail.observe(inner); quote.push(inner); i++;
        }
        const callout = quote[0].match(/^\[!(NOTE|TIP|IMPORTANT|WARNING|CAUTION)\][ \t]*(.*)$/i);
        if (callout) {
          const name = callout[1].toLowerCase(); quote.shift();
          const label = callout[2] || name[0].toUpperCase() + name.slice(1);
          push({kind: 'callout', name, label, children: parseBlocks(quote, depth + 1)});
        } else push({kind: 'quote', children: parseBlocks(quote, depth + 1)});
        continue;
      }
      const marker = listMarker(line);
      if (marker) {
        const items = []; let loose = false;
        while (i < lines.length) {
          const next = listMarker(lines[i]);
          if (!next || next.ordered !== marker.ordered || next.indent !== marker.indent || next.marker.at(-1) !== marker.marker.at(-1)) break;
          const item = [next.text], tail = containerTail(depth); i++; let blank = false;
          tail.observe(next.text.replace(/^\[([ xX])\](?:\s+|$)/, ''));
          while (i < lines.length) {
            if (blankLine(lines[i])) {
              if (tail.literalBlank()) {
                const inner = stripIndent(lines[i++], next.width);
                tail.observe(inner); item.push(inner); continue;
              }
              let j = i; while (j < lines.length) { charge(lines[j].length + 1); if (!blankLine(lines[j])) break; j++; }
              const following = j < lines.length && listMarker(lines[j]);
              const continued = j < lines.length && indentation(lines[j]).width >= next.width;
              if (!continued && !(following && following.indent === marker.indent && following.ordered === marker.ordered && following.marker.at(-1) === marker.marker.at(-1))) break;
              blank = true;
              // Consume a blank run once; repeated suffix lookahead is quadratic.
              while (i < j) { tail.observe(''); item.push(''); i++; }
              continue;
            }
            if (indentation(lines[i]).width >= next.width) {
              const inner = stripIndent(lines[i++], next.width);
              const nested = listMarker(inner);
              // Properly indented ordered children may start at any number.
              // Keep later items of an existing ordered child list together.
              if (!tail.literal() && nested && nested.ordered && nested.start !== 1
                && !blankLine(item.at(-1)) && !listMarker(item.at(-1))) {
                tail.observe(''); item.push('');
              }
              tail.observe(inner); item.push(inner); continue;
            }
            const sibling = listMarker(lines[i]);
            if ((sibling && sibling.indent === marker.indent && sibling.ordered === marker.ordered)
              || !tail.canContinue(lines[i])) break;
            const lazy = lazyLine(lines[i++]);
            tail.observe(lazy); item.push(lazy);
          }
          const task = item[0].match(/^\[([ xX])\](?:\s+|$)(.*)$/);
          if (task) item[0] = task[2];
          allocate();
          items.push({task: task ? task[1] !== ' ' : null, children: parseBlocks(item, depth + 1)});
          loose ||= blank;
        }
        push({kind: 'list', ordered: marker.ordered, start: marker.start, loose, items}); continue;
      }
      const aligns = i + 1 < lines.length && tableAlignments(line, lines[i + 1]);
      if (aligns) {
        const head = tableCells(line), rows = [];
        i += 2;
        while (i < lines.length && tableRowSource(lines[i])) {
          allocate(); rows.push(tableCells(lines[i++]));
        }
        push({kind: 'table', aligns, head, rows}); continue;
      }
      const paragraph = [line]; i++;
      let underline = 0;
      while (i < lines.length) {
        underline = setextLevel(lines[i]);
        if (underline) { i++; break; }
        if (interruptsParagraph(lines[i]) || (i + 1 < lines.length && tableAlignments(lines[i], lines[i + 1]))) break;
        paragraph.push(lines[i++]);
      }
      push(underline ? {kind: 'heading', title: paragraph.join('\n'), level: underline}
        : {kind: 'paragraph', text: paragraph.join('\n')});
    }
    return out;
  }
  function renderBlocks(nodes, tight = false, footnotes = true) {
    let out = '';
    for (const node of nodes) {
      charge();
      switch (node.kind) {
        case 'fallback':
          out = append(out, append(append('<pre>', escape(node.text)), '</pre>\n')); break;
        case 'code':
          out = append(out, '<pre><code' + (node.lang ? ' class="language-' + escape(node.lang) + '"' : '')
            + '>' + escape(node.text) + '</code></pre>\n'); break;
        case 'html':
          // Preserve the existing lightweight policy: markup stays visible and
          // inert. Its literal body must never pass through Markdown inlining,
          // definition collection, image resolution, or heading-ID allocation.
          out = append(out, '<p>' + escape(node.text) + '</p>\n'); break;
        case 'heading': {
          const content = inline(node.title, 0, true, footnotes);
          const slug = decode(content.replace(/<[^>]*>/g, '')).toLowerCase().replace(/[^\p{L}\p{N}_\s-]/gu, '').trim().replace(/\s+/g, '-') || 'section';
          out = append(out, '<h' + node.level + ' id="' + escape(uniqueId(slug)) + '">' + content + '</h' + node.level + '>\n'); break;
        }
        case 'rule': out = append(out, '<hr>\n'); break;
        case 'callout':
          out = append(out, '<aside class="callout callout-' + node.name + '"><p class="callout-title">'
            + inline(node.label, 0, true, footnotes) + '</p>\n' + renderBlocks(node.children, false, footnotes) + '</aside>\n'); break;
        case 'quote':
          out = append(out, '<blockquote>\n' + renderBlocks(node.children, false, footnotes) + '</blockquote>\n'); break;
        case 'list': {
          const tag = node.ordered ? 'ol' : 'ul';
          out = append(out, '<' + tag + (node.ordered && node.start !== 1 ? ' start="' + node.start + '"' : '') + '>\n');
          for (const item of node.items) {
            let content = renderBlocks(item.children, !node.loose, footnotes);
            if (item.task !== null) {
              const checkbox = '<input type="checkbox" disabled' + (item.task ? ' checked' : '') + '> ';
              content = content.startsWith('<p>') ? '<p>' + checkbox + content.slice(3) : checkbox + content;
            }
            out = append(out, '<li' + (item.task !== null ? ' class="task"' : '') + '>' + content.replace(/\n$/, '') + '</li>\n');
          }
          out = append(out, '</' + tag + '>\n'); break;
        }
        case 'table': {
          const row = (cells, tag) => {
            let html = '<tr>';
            for (let index = 0; index < node.aligns.length; index++) {
              const align = node.aligns[index];
              html = append(html, '<' + tag + (align ? ' style="text-align:' + align + '"' : '') + '>'
                + inline(cells[index] || '', 0, true, footnotes, true, true) + '</' + tag + '>');
            }
            return append(html, '</tr>\n');
          };
          out = append(out, '<div class="table-wrap" role="region" aria-label="Markdown table" tabindex="0"><table>\n<thead>\n'
            + row(node.head, 'th') + '</thead>\n<tbody>\n');
          for (const cells of node.rows) out = append(out, row(cells, 'td'));
          out = append(out, '</tbody>\n</table></div>\n'); break;
        }
        case 'paragraph': {
          const content = inline(node.text, 0, true, footnotes);
          out = append(out, tight ? content + '\n' : '<p>' + content + '</p>\n'); break;
        }
      }
    }
    return out;
  }
  function documentBody(text) {
    // Match native document_body/split_frontmatter before newline conversion:
    // only the document's initial BOM is ignorable content. Frontmatter has
    // its own optional BOM admission; a later BOM in the body stays literal.
    const body = text[0] === '\ufeff' ? text.slice(1) : text;
    const candidate = body[0] === '\ufeff' ? body.slice(1) : body;
    if (!candidate.startsWith('---')) return body;
    let cursor = 0;
    const nextLine = () => {
      const start = cursor;
      while (cursor < candidate.length && candidate[cursor] !== '\r' && candidate[cursor] !== '\n') { charge(); cursor++; }
      const end = cursor;
      // LF, lone CR and CRLF each end one logical line, preserving the exact
      // original suffix after metadata instead of normalizing source offsets.
      if (candidate[cursor] === '\r') { charge(); cursor++; }
      if (candidate[cursor] === '\n') { charge(); cursor++; }
      return candidate.slice(start, end);
    };
    if (nextLine() !== '---') return body;
    // Rust's metadata trim uses Unicode White_Space, which does not include
    // U+FEFF. JavaScript trim() would incorrectly reject that nonempty key.
    const trim = value => {
      let start = 0, end = value.length;
      while (start < end && /\p{White_Space}/u.test(value[start])) { charge(); start++; }
      while (end > start && /\p{White_Space}/u.test(value[end - 1])) { charge(); end--; }
      return value.slice(start, end);
    };
    let sawAssignment = false, scalarParent = null, scalarIndent = null, leadingBlankIndent = 0;
    while (cursor < candidate.length) {
      const line = nextLine();
      if (line === '---') return sawAssignment ? candidate.slice(cursor) : body;
      charge(line.length * 3 + 1);
      const blank = /^[ \t]*$/.test(line);
      let indent = 0;
      while (line[indent] === ' ') { charge(); indent++; }
      if (scalarParent !== null && (blank || indent > scalarParent)) {
        if (blank && scalarIndent === null) leadingBlankIndent = Math.max(leadingBlankIndent, indent);
        else if (scalarIndent === null) {
          scalarIndent = indent;
          if (leadingBlankIndent > indent) return body;
        } else if (!blank && indent < scalarIndent) return body;
        continue;
      }
      scalarParent = null;
      if (blank || /^[ \t]*#/.test(line)) continue;
      const separator = line.search(/[=:]/);
      if (separator < 0 || !trim(line.slice(0, separator))) return body;
      sawAssignment = true;
      const value = trim(line.slice(separator + 1));
      const comment = value.search(/(?:^|\p{White_Space})#/u);
      const header = trim(comment < 0 ? value : value.slice(0, comment));
      if (/^[|>][+-]?$/.test(header)) {
        scalarParent = indent; scalarIndent = null; leadingBlankIndent = 0;
      }
    }
    // Empty/comment-only, unsupported, malformed and unclosed candidates are
    // ordinary Markdown in full. No definition state was touched speculatively.
    return body;
  }
  const lines = documentBody(source).replace(/\r\n?/g, '\n').replace(/\0/g, '\ufffd').split('\n');
  const body = renderBlocks(parseBlocks(lines));
  if (!usedNotes.length) return body;
  // Render the growing work queue once per note, then emit all backlinks.
  // Nested notes can append work; cycles only append references, never work.
  const renderedNotes = [];
  for (let index = 0; index < usedNotes.length; index++) renderedNotes.push(renderBlocks(usedNotes[index].content));
  let footer = '<section class="footnotes" role="doc-endnotes"><hr><ol>\n';
  usedNotes.forEach((note, index) => {
    let backlinks = '';
    for (let ref = 1; ref <= note.references; ref++) {
      const id = note.referenceIds[ref - 1];
      backlinks = append(backlinks, ' <a href="#' + id + '" class="footnote-backref" role="doc-backlink" aria-label="Back to reference ' + note.number + (ref > 1 ? '-' + ref : '') + '">↩</a>');
    }
    footer = append(footer, '<li id="' + note.id + '">' + renderedNotes[index] + backlinks + '</li>\n');
  });
  return append(append(body, footer), '</ol></section>\n');
}

// Only self-contained image payloads, never HTML, script, blob/file URLs or
// a remotely fetched URL, may be stored in an explicit workspace binding.
// Keep this separate from link admission: data images are not active links.
function fmdEmbeddedImageUrl(uri) {
  if (typeof uri !== 'string' || !/^data:image\/(?:png|jpeg|gif|webp|svg\+xml);base64,/i.test(uri)) return false;
  const data = uri.slice(uri.indexOf(',') + 1);
  if (!data.length || data.length % 4 || !/^[A-Za-z0-9+/]*={0,2}$/.test(data) || /[\r\n]/.test(data)) return false;
  // Canonical padding cannot hide additional nonzero bits. Keep saved bindings
  // canonical; only source URLs use the normalization path below.
  const padding = data.endsWith('==') ? 2 : data.endsWith('=') ? 1 : 0;
  const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
  return data.length / 4 * 3 - padding <= 32 * 1024 * 1024
    && (!padding || !(alphabet.indexOf(data[data.length - padding - 1]) & (padding === 2 ? 15 : 3)));
}

function fmdDataImageMime(uri) {
  if (typeof uri !== 'string' || !/^data:/i.test(uri)) return null;
  const header = uri.slice(0, 256), end = header.search(/[;,]/);
  const mime = end < 0 ? '' : header.slice(5, end).toLowerCase();
  return /^(?:image\/(?:png|jpeg|gif|webp)|image\/svg\+xml)$/.test(mime) ? mime : null;
}

// Source images may use UTF-8/percent-escaped bytes or percent-escaped base64,
// just like native HTML. Normalize only the emitted img attribute: source and
// saved Markdown stay exact. This is bounded URL decoding, not an image decoder
// or an HTML sanitizer; the browser still validates image pixels. SVG remains
// an inert image subresource and never becomes markup in the workspace.
function fmdNormalizeSourceImage(uri, charge, exhausted, outputLimit) {
  const mime = fmdDataImageMime(uri), comma = uri.slice(0, 256).indexOf(',');
  if (!mime || comma < 0) return null;
  let base64 = false, charset = false;
  for (const field of uri.slice(5, comma).split(';').slice(1)) {
    if (/^base64$/i.test(field) && !base64) base64 = true;
    else if (/^charset=utf-8$/i.test(field) && !charset && !base64) charset = true;
    else return null;
  }
  // Debit decoding before allocating an output buffer. Chunked emission bounds
  // intermediate strings and avoids spreading a whole image into function args.
  charge(uri.length - comma - 1);
  const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
  const prefix = 'data:' + mime + ';base64,', parts = [prefix];
  let chunk = '', size = prefix.length, decoded = 0;
  const emit = value => {
    if (value.length > outputLimit - size) exhausted('output');
    charge(value.length); size += value.length; chunk += value;
    if (chunk.length >= 8192) { parts.push(chunk); chunk = ''; }
  };
  const hex = code => code >= 48 && code <= 57 ? code - 48
    : code >= 65 && code <= 70 ? code - 55 : code >= 97 && code <= 102 ? code - 87 : -1;
  let value = 0, used = 0, padded = false;
  const quartet = [];
  const byte = number => {
    if (base64) {
      if (padded || number !== 61 && alphabet.indexOf(String.fromCharCode(number)) < 0) return false;
      quartet.push(number);
      if (quartet.length === 4) {
        const [a, b, c, d] = quartet;
        if (a === 61 || b === 61 || c === 61 && d !== 61) return false;
        const padding = c === 61 ? 2 : d === 61 ? 1 : 0;
        const last = alphabet.indexOf(String.fromCharCode(padding === 2 ? b : c));
        if (padding && last & (padding === 2 ? 15 : 3)) return false;
        decoded += 3 - padding;
        if (decoded > 32 * 1024 * 1024) exhausted('image bytes');
        emit(String.fromCharCode(a, b, c, d));
        padded = padding > 0; quartet.length = 0;
      }
    } else {
      if (++decoded > 32 * 1024 * 1024) exhausted('image bytes');
      value = (value << 8) | number;
      if (++used === 3) {
        emit(alphabet[(value >>> 18) & 63] + alphabet[(value >>> 12) & 63]
          + alphabet[(value >>> 6) & 63] + alphabet[value & 63]);
        used = 0; value = 0;
      }
    }
    return true;
  };
  for (let i = comma + 1; i < uri.length; i++) {
    const code = uri.charCodeAt(i);
    if (code === 37) {
      const high = hex(uri.charCodeAt(i + 1)), low = hex(uri.charCodeAt(i + 2));
      if (high < 0 || low < 0 || !byte(high * 16 + low)) return null;
      i += 2;
    } else if (code < 128) {
      if (!byte(code)) return null;
    } else {
      if (base64) return null;
      const scalar = uri.codePointAt(i);
      if (scalar >= 0xd800 && scalar <= 0xdfff) return null;
      if (scalar < 0x800) { byte(0xc0 | scalar >> 6); byte(0x80 | scalar & 63); }
      else if (scalar < 0x10000) {
        byte(0xe0 | scalar >> 12); byte(0x80 | scalar >> 6 & 63); byte(0x80 | scalar & 63);
      } else {
        byte(0xf0 | scalar >> 18); byte(0x80 | scalar >> 12 & 63);
        byte(0x80 | scalar >> 6 & 63); byte(0x80 | scalar & 63); i++;
      }
    }
  }
  if (!decoded || quartet.length) return null;
  if (!base64 && used) {
    emit(used === 1 ? alphabet[value >> 2] + alphabet[(value & 3) << 4] + '=='
      : alphabet[value >> 10] + alphabet[(value >> 4) & 63] + alphabet[(value & 15) << 2] + '=');
  }
  if (chunk) parts.push(chunk);
  return parts.join('');
}
