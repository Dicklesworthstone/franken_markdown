"""Generate native/offline reference-label folding from pinned Unicode data.

Run with Python 3; --check verifies both generated outputs without writing.
No network access or Python Unicode database is used. Only default full C+F
mappings are selected; unlisted scalars stay unchanged, with no normalization.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VERSION = "17.0.0"
DATA_SHA256 = "ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183"
FIXTURES = ROOT / "tests/fixtures/unicode"
data = (FIXTURES / f"CaseFolding-{VERSION}.txt").read_bytes()
if hashlib.sha256(data).hexdigest() != DATA_SHA256:
    raise SystemExit("Pinned CaseFolding data checksum mismatch")
license_text = (FIXTURES / "LICENSE.txt").read_text(encoding="utf-8").strip()
pairs = []
for line in data.decode("utf-8").splitlines():
    fields = [field.strip() for field in line.split("#", 1)[0].split(";")]
    if len(fields) >= 3 and fields[1] in ("C", "F"):
        pairs.append((int(fields[0], 16), "".join(chr(int(cp, 16)) for cp in fields[2].split())))
if len(pairs) != 1585 or pairs != sorted(set(pairs)):
    raise SystemExit("Expected the complete sorted Unicode 17.0.0 C+F mapping")

# Compress same-delta runs without including any scalar that folds differently.
# Stride-two intervals leave the interleaved identity scalars unchanged.
singles = [(cp, ord(value) - cp) for cp, value in pairs if len(value) == 1]
ranges = []
i = 0
while i < len(singles):
    cp, delta = singles[i]
    end, stride = i + 1, 1
    for step in (1, 2):
        j = i + 1
        while (j < len(singles) and singles[j][0] == singles[j - 1][0] + step
               and singles[j][1] == delta):
            j += 1
        if j > end:
            end, stride = j, step
    ranges.append((cp, singles[end - 1][0], stride, delta))
    i = end
expansions = [(cp, value) for cp, value in pairs if len(value) != 1]
header = f'''// Generated by scripts/generate-reference-casefold.py; do not edit.
// Unicode {VERSION} default FULL case folding (C+F, excluding Turkic T).
// https://www.unicode.org/Public/{VERSION}/ucd/CaseFolding.txt
// SHA-256: {DATA_SHA256}
// No locale tailoring, normalization, or host-runtime casing database.
/*
{license_text}
*/
'''

rust_ranges = "\n".join(f"    (0x{lo:x}, 0x{hi:x}, {step}, {delta})," for lo, hi, step, delta in ranges)
rust_expansions = "\n".join(
    f'    (0x{cp:x}, "' + "".join(f"\\u{{{ord(ch):x}}}" for ch in value) + '"),'
    for cp, value in expansions
)
rust = header + '''
// Sorted, non-overlapping inclusive ranges: (first, last, stride, delta).
#[rustfmt::skip]
const RANGES: &[(u32, u32, u32, i32)] = &[
''' + rust_ranges + '''
];

#[rustfmt::skip]
const EXPANSIONS: &[(u32, &str)] = &[
''' + rust_expansions + '''
];

/// Append the pinned default full fold of one Unicode scalar.
pub(super) fn push(ch: char, out: &mut String) {
    if ch.is_ascii() {
        out.push(ch.to_ascii_lowercase());
        return;
    }
    let cp = u32::from(ch);
    if let Ok(index) = EXPANSIONS.binary_search_by_key(&cp, |&(code, _)| code) {
        out.push_str(EXPANSIONS[index].1);
        return;
    }
    let mut low = 0;
    let mut high = RANGES.len();
    while low < high {
        let mid = (low + high) / 2;
        let (first, last, stride, delta) = RANGES[mid];
        if cp < first {
            high = mid;
        } else if cp > last {
            low = mid + 1;
        } else {
            let folded = if (cp - first) % stride == 0 {
                cp.checked_add_signed(delta)
                    .and_then(char::from_u32)
                    .unwrap_or(ch)
            } else {
                ch
            };
            out.push(folded);
            return;
        }
    }
    out.push(ch);
}

#[cfg(test)]
#[path = "unicode_casefold_tests.rs"]
mod tests;
'''
js_ranges = "\n".join(f"  [0x{lo:x}, 0x{hi:x}, {step}, {delta}]," for lo, hi, step, delta in ranges)
js_expansions = "\n".join(f"  [0x{cp:x}, {json.dumps(value, ensure_ascii=True)}]," for cp, value in expansions)
javascript = header + '''
// Sorted, non-overlapping inclusive ranges: [first, last, stride, delta].
const FMD_REFERENCE_FOLD_RANGES = [
''' + js_ranges + '''
];
const FMD_REFERENCE_FOLD_EXPANSIONS = new Map([
''' + js_expansions + '''
]);

// Input is one source Unicode scalar, already charged to the parser budget.
function fmdFoldReferenceScalar(cp) {
  if (cp < 128) return String.fromCodePoint(cp >= 65 && cp <= 90 ? cp + 32 : cp);
  const expansion = FMD_REFERENCE_FOLD_EXPANSIONS.get(cp);
  if (expansion !== undefined) return expansion;
  let low = 0, high = FMD_REFERENCE_FOLD_RANGES.length;
  while (low < high) {
    const mid = (low + high) >>> 1, [first, last, stride, delta] = FMD_REFERENCE_FOLD_RANGES[mid];
    if (cp < first) high = mid;
    else if (cp > last) low = mid + 1;
    else return String.fromCodePoint((cp - first) % stride === 0 ? cp + delta : cp);
  }
  return String.fromCodePoint(cp);
}
'''
js_path = ROOT / "src/interactive_renderer.js"
source = js_path.read_text(encoding="utf-8")
start_marker = "// BEGIN GENERATED REFERENCE CASE FOLDING\n"
end_marker = "// END GENERATED REFERENCE CASE FOLDING\n"
if source.count(start_marker) != 1 or source.count(end_marker) != 1:
    raise SystemExit("Expected exactly one generated reference-folding region")
start = source.index(start_marker) + len(start_marker)
end = source.index(end_marker, start)
outputs = {
    ROOT / "src/parse/unicode_casefold.rs": rust,
    js_path: source[:start] + javascript + source[end:],
}
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
for path, content in outputs.items():
    if args.check:
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            raise SystemExit(f"Generated reference-folding output is stale: {path.relative_to(ROOT)}")
    else:
        path.write_text(content, encoding="utf-8")
print(f"Unicode {VERSION}: {len(pairs)} mappings, {len(ranges)} ranges, {len(expansions)} expansions; "
      + ("outputs verified" if args.check else "outputs regenerated"))
